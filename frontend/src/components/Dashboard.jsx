import { useEffect, useState } from "react";
import { Loader2, AlertCircle, History, RefreshCw } from "lucide-react";
import { api } from "../api/client.js";
import { StatusBadge } from "./FindingCard.jsx";

export default function Dashboard({ ai, onOpen, onNew, refreshKey }) {
  const [rules, setRules] = useState([]);
  const [scans, setScans] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [opening, setOpening] = useState("");

  async function load() {
    setLoading(true);
    setError("");
    try {
      const [r, s] = await Promise.all([api.rules(), api.scans()]);
      setRules(r);
      setScans(s);
    } catch (e) {
      setError(e.message);
    } finally {
      setLoading(false);
    }
  }
  useEffect(() => { load(); }, [refreshKey]);

  async function open(id) {
    setOpening(id);
    try { onOpen(await api.scan(id)); } catch (e) { setError(e.message); } finally { setOpening(""); }
  }

  const sorted = [...scans].sort((a, b) => (Date.parse(b.created_at) || 0) - (Date.parse(a.created_at) || 0));
  const latest = sorted[0];
  const statusOf = (id) => latest?.findings.find((f) => f.rule_id === id)?.status || "NOT_VERIFIED";
  const stats = [
    ["Total scans", scans.length],
    ["Passed requirements", latest ? latest.counts.passed : "–"],
    ["Findings", latest ? latest.counts.failed : "–"],
    ["Not verified", latest ? latest.counts.not_verified : "–"],
  ];

  return (
    <section className="page">
      <div className="row between">
        <h1>Dashboard</h1>
        <div className="row">
          <button className="btn secondary" onClick={load} disabled={loading}><RefreshCw size={16} /> Refresh</button>
          <button className="btn primary" onClick={onNew}>New scan</button>
        </div>
      </div>
      {error && <div className="alert" role="alert"><AlertCircle size={18} /> {error}</div>}
      {loading && <p className="muted"><Loader2 size={16} className="spin" /> Loading…</p>}
      <div className="grid stats">
        {stats.map(([l, v]) => (<div className="card stat" key={l}><strong>{v}</strong><span className="muted">{l}</span></div>))}
      </div>
      <div className={`card notice ${ai ? "" : "warn"}`}>
        {ai === null ? "Checking AI status…" : ai ? "Local AI assistant is available." : "The local AI assistant is unavailable. Fallback explanations are being used; they are not generated by AI."}
      </div>
      <h2>Latest assessment</h2>
      {latest ? (
        <div className="card row between">
          <div><strong>{latest.filename}</strong><p className="muted small">{latest.created_at || "Date not provided"}</p></div>
          <button className="btn secondary" onClick={() => open(latest.scan_id)} disabled={opening === latest.scan_id}>Open results</button>
        </div>
      ) : <p className="muted">No scans yet. Upload a project to create your first assessment.</p>}

      <h2>OWASP compliance overview</h2>
      <p className="muted small">Requirements are listed exactly as configured in the backend. Status reflects the latest assessment.</p>
      <div className="card table-wrap">
        <table>
          <thead><tr><th>ID</th><th>Requirement</th><th>Status</th></tr></thead>
          <tbody>
            {rules.length === 0 && <tr><td colSpan="3" className="muted">No requirements loaded.</td></tr>}
            {rules.map((r) => (<tr key={r.rule_id}><td>{r.rule_id}</td><td>{r.title}</td><td><StatusBadge status={latest ? statusOf(r.rule_id) : "NOT_VERIFIED"} /></td></tr>))}
          </tbody>
        </table>
      </div>

      <h2><History size={20} /> Scan history</h2>
      <p className="muted small">Scans from this browser session. The session ID is a demo identifier, not authentication.</p>
      <div className="card table-wrap">
        <table>
          <thead><tr><th>File</th><th>Date</th><th>Passed</th><th>Findings</th><th>Not verified</th><th></th></tr></thead>
          <tbody>
            {sorted.length === 0 && <tr><td colSpan="6" className="muted">No previous scans.</td></tr>}
            {sorted.map((s) => (
              <tr key={s.scan_id}>
                <td>{s.filename}</td><td>{s.created_at || "n/a"}</td>
                <td>{s.counts.passed}</td><td>{s.counts.failed}</td><td>{s.counts.not_verified}</td>
                <td><button className="btn small-btn" onClick={() => open(s.scan_id)} disabled={opening === s.scan_id}>Reopen</button></td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}
